"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const http = require("node:http");
const { randomUUID } = require("node:crypto");
const { fixture } = require("../tools/upload-review-fixture.cjs");
test("uploaded video goes through analysis, a separate Q4 Preview production, Gemini review and cached resume", async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "drama-upload-"));
  const { router, requests } = fixture(root);
  const server = http.createServer((req, res) => router.route(req, res));
  await new Promise(r => server.listen(0, "127.0.0.1", r));
  t.after(async () => { await new Promise(r => server.close(r)); fs.rmSync(root, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}/api/drama`;
  const post = (url, body) => fetch(base + url, { method: "POST", body: JSON.stringify(body) });
  assert.equal((await post("/projects", { uploadIntent: "invalid" })).status, 400);
  const source = await (await post("/projects", { uploadIntent: "remake", title: "Upload test", brief: "Modern city realism", rightsConfirmed: true })).json();
  const url = `/projects/${source.id}`;
  assert.equal((await fetch(base + url + "/episodes", { method: "POST", body: "" })).status, 400);
  assert.equal((await fetch(base + url + "/episodes?title=customer.mp4", { method: "POST", body: "mock video" })).status, 201);
  assert.equal((await post(url + "/run", { stage: "all" })).status, 409, "Source project must not use legacy 720p generation");
  assert.equal((await post(url + "/run", { stage: "analyze" })).status, 202); await router.engine.active.get(source.id);
  const analyzed = router.store.get(source.id);
  assert.equal(analyzed.job.status, "completed", analyzed.job.error); assert.equal(analyzed.episodes[0].shots.length, 4); assert.equal(requests.length, 0);
  const original = structuredClone(analyzed.episodes), requestId = randomUUID();
  const options = { requestId, episodes: [{ id: analyzed.episodes[0].id, style: "cinematic" }], continuity: true };
  const copy = await (await post(url + "/production", options)).json();
  const retry = await (await post(url + "/production", options)).json(); assert.equal(copy.id, retry.id);
  assert.equal(copy.production.referenceModel, "viduq4-preview"); assert.equal(copy.production.imageModel, "viduq4-preview");
  assert.equal(copy.production.generationSeconds, 16); assert.equal(copy.production.resolution, "2K"); assert.equal(copy.aspectRatio, "9:16");
  assert.match(copy.brief, /Modern city realism/);
  assert.deepEqual(analyzed.episodes, original); assert.equal(analyzed.uploadWorkflow.productionProjectId, copy.id);
  const generated = router.store.get(copy.id);
  assert.equal((await post(`/projects/${copy.id}/run`, { stage: "all" })).status, 202); await router.engine.active.get(copy.id);
  assert.equal(generated.job.status, "completed", generated.job.error); assert.equal(generated.deliveries.length, 1);
  assert.equal(generated.deliveries[0].visualReview.verdict, "pass");
  const videos = requests.filter(r => r.payload.model === "viduq4-preview");
  assert.equal(videos.length, 2); assert.ok(videos.some(r => r.endpoint.endsWith("reference2video"))); assert.ok(videos.some(r => r.endpoint.endsWith("img2video")));
  assert.ok(videos.every(r => r.payload.duration === 16 && r.payload.resolution === "2K"));
  const count = requests.length;
  await post(`/projects/${copy.id}/run`, { stage: "all" }); await router.engine.active.get(copy.id); assert.equal(requests.length, count);
  const delivery = generated.deliveries[0];
  assert.equal((await post(`/projects/${copy.id}/deliveries/${delivery.id}/review`, {})).status, 400);
  assert.equal((await post(`/projects/${copy.id}/deliveries/${delivery.id}/review`, { confirmPaid: true })).status, 202); await router.engine.active.get(copy.id);
  assert.equal(generated.job.status, "completed"); assert.equal(requests.length, count); assert.deepEqual(analyzed.episodes, original);
});
